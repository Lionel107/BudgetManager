-- ============================================================================
-- BudgetManager — Régularisation des comptes
--   Quand on a perdu le fil de sa compta, on recale chaque compte sur son solde
--   RÉEL (celui de la banque). L'écart n'est PAS enregistré comme une dépense ou
--   un revenu (les budgets et statistiques restent justes) : il est conservé dans
--   un historique, que l'app et le copilote IA consultent.
-- Ré-exécutable (IF NOT EXISTS / OR REPLACE).
-- ============================================================================

create table if not exists public.account_regularizations (
    id               bigint generated by default as identity primary key,
    user_id          uuid not null default auth.uid() references auth.users(id) on delete cascade,
    account_id       bigint not null references public.accounts(id) on delete cascade,
    regularized_at   timestamptz not null default now(),
    previous_balance numeric(15, 2) not null,   -- solde dans l'app avant
    real_balance     numeric(15, 2) not null,   -- solde réel saisi
    difference       numeric(15, 2) not null,   -- real - previous (négatif = argent non suivi parti)
    note             text,
    created_at       timestamptz not null default now()
);
create index if not exists account_regularizations_user_idx
    on public.account_regularizations (user_id, regularized_at desc);

-- RLS : propriétaire uniquement
alter table public.account_regularizations enable row level security;
drop policy if exists owner_all on public.account_regularizations;
create policy owner_all on public.account_regularizations
    for all using (user_id = auth.uid()) with check (user_id = auth.uid());

-- Recale un compte sur son solde réel + trace l'écart, en une seule transaction.
-- SECURITY INVOKER : la RLS s'applique (impossible de toucher le compte d'autrui).
-- Renvoie l'écart appliqué (réel − ancien).
create or replace function public.regularize_account(
    p_account_id   bigint,
    p_real_balance numeric,
    p_note         text default null
)
returns numeric
language plpgsql
security invoker
as $$
declare
    v_previous numeric;
begin
    select balance into v_previous
    from public.accounts
    where id = p_account_id
    for update;

    if not found then
        raise exception 'Compte introuvable';
    end if;

    insert into public.account_regularizations (account_id, previous_balance, real_balance, difference, note)
    values (p_account_id, v_previous, p_real_balance, p_real_balance - v_previous, nullif(trim(p_note), ''));

    update public.accounts set balance = p_real_balance where id = p_account_id;

    return p_real_balance - v_previous;
end;
$$;
